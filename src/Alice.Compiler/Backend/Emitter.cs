using System.Text;
using Alice.Compiler.Lowering;
using Alice.Compiler.Mir;
using Alice.Compiler.Optimizer;
using Alice.Compiler.Semantics;
using Alice.Compiler.Syntax;

namespace Alice.Compiler.Backend;

/// <summary>Emits one C# compilation unit per Alice file: declarations from symbols, bodies from MIR.</summary>
public sealed class Emitter
{
    readonly Binder binder;
    readonly Lowerer lowerer;
    string file = "";
    bool moduleAttrsEmitted;
    public readonly CEmitter Native = new();
    public string NativeLib = "alice_native";
    bool nativeProbeEmitted;

    public Emitter(Binder binder)
    {
        this.binder = binder;
        lowerer = new Lowerer(binder);
    }

    const string Header =
        "// <auto-generated> Alice compiler </auto-generated>\n" +
        "#nullable enable\n" +
        "#pragma warning disable CS0105, CS0162, CS0164, CS0168, CS0219, CS0618, CS0660, CS0661, CS8618, CS8632, CS1717, CS8981\n" +
        "using System;\nusing System.Collections.Generic;\nusing System.Linq;\nusing System.Text;\nusing System.IO;\nusing System.Threading;\nusing System.Threading.Tasks;\nusing Alice.Runtime;\nusing static Alice.Runtime.Prelude;\nusing static Program;\n";

    int classBodyN;

    /// <summary>Types with executable class bodies, in declaration order (nested and namespaced included).</summary>
    static IEnumerable<TypeSym> ClassBodies(IEnumerable<Item> items)
    {
        foreach (var it in items)
        {
            if (it is NamespaceItem ns) foreach (var t in ClassBodies(ns.Items)) yield return t;
            if (it is not TypeDecl { Sym: TypeSym ts } td) continue;
            if (td.Members.Any(m => m is MethodDecl { Name: "__class_body" })) yield return ts;
            foreach (var t in ClassBodies(td.Members)) yield return t;
        }
    }

    bool gpuHostEmitted;

    public string EmitFile(FileNode f)
    {
        file = f.Path;
        lowerer.File = f.Path;
        var sb = new StringBuilder(Header);
        foreach (var it in f.Items)
            if (it is UsingItem u)
            {
                sb.Append(UsingLine(u.Name));
                if (binder.Extensions.Any(x => x.RefineScope == u.Name)) sb.Append($"using __Refine_{u.Name};\n");   // its refinements
            }
        if (!moduleAttrsEmitted)
        {
            // Alice guarantees definite assignment, so zero-initialising locals/stackalloc is wasted work.
            sb.Append("[module: global::System.Runtime.CompilerServices.SkipLocalsInit]\n");
            moduleAttrsEmitted = true;
        }
        var prog = new StringBuilder();
        Items(sb, prog, f.Items);
        // refinements: extension classes in `__Refine_<module>`, so only files with `using <module>` see them in C# too
        if (lowerer.UsesGpu && !gpuHostEmitted)   // the shared accelerator, once per program
        {
            sb.Append(Lowering.Lowerer.GpuHost);
            gpuHostEmitted = true;
        }
        foreach (var r in Refinements(f.Items))
            sb.Append($"namespace __Refine_{r.RefineScope}\n{{\n{Type(r)}}}\n");
        var bodies = ClassBodies(f.Items).ToList();
        if (bodies.Count > 0)
            prog.Append($"[global::System.Runtime.CompilerServices.ModuleInitializer]\ninternal static void __alice_class_bodies{classBodyN++}()\n{{\n")
                .Append(string.Concat(bodies.Select(t => $"    {t.Type.Cs}.__class_body();\n"))).Append("}\n");
        if (!Native.IsEmpty && !nativeProbeEmitted)
        {
            prog.Append($"public static bool __alice_native_loaded() => global::Alice.Runtime.NativeLibs.IsLoaded(\"{NativeLib}\");\n");
            nativeProbeEmitted = true;
        }
        sb.Append("public static partial class Program\n{\n").Append(prog);
        var main = f.Items.OfType<StmtItem>().Select(s => s.Stmt).ToList();
        if (main.Count > 0)
        {
            lowerer.Type = binder.Program;
            lowerer.Method = null;
            var body = lowerer.LowerBody(main, Tail.None, f.HoistedLocals, main[0].Line);
            sb.Append("public static void Main(string[] ARGV)\n{\nPrelude.init();\nPrelude.ARGV = ARGV;\n").Append(Print(body, 1)).Append("}\n");
            sb.Append(string.Concat(lowerer.Extra));
            lowerer.Extra.Clear();
        }
        sb.Append("}\n");
        return sb.ToString();
    }

    /// <summary>`using X` on a type (an Alice module, a static class) imports its members, like Ruby's include.</summary>
    static IEnumerable<TypeDecl> Refinements(IEnumerable<Item> items)
    {
        foreach (var it in items)
        {
            if (it is TypeDecl { RefineScope: not null } r) yield return r;
            if (it is TypeDecl td) foreach (var x in Refinements(td.Members)) yield return x;
            if (it is NamespaceItem n) foreach (var x in Refinements(n.Items)) yield return x;
        }
    }

    string UsingLine(string name) =>
        binder.IsTypeName(name) ? $"using static {binder.ResolveType(new TypeRef { Name = name }).Cs};\n" : $"using {name};\n";

    string Print(List<MStmt> body, int ind)
    {
        Optimizer.Pipeline.Run(body);
        var p = new Printer(file, ind);
        p.Stmts(body);
        return p.ToString();
    }

    void Items(StringBuilder types, StringBuilder prog, List<Item> items)
    {
        foreach (var it in items)
        {
            switch (it)
            {
                case NamespaceItem n:
                    {
                        var inner = new StringBuilder();
                        foreach (var u in n.Items.OfType<UsingItem>()) inner.Append(UsingLine(u.Name));
                        Items(inner, prog, n.Items);
                        types.Append($"namespace {n.Name}\n{{\n{inner}}}\n");
                        break;
                    }
                case TypeDecl d: types.Append(Type(d)); break;
                case EnumDecl e: types.Append(Enum(e)); break;
                case LibDecl l: types.Append(Lib(l)); break;
                case DelegateDecl dg:
                    {
                        var inv = ((TypeSym)dg.Sym!).Methods["Invoke"][0];
                        string r = inv.Ret.IsVoid ? "void" : inv.Ret.Cs;
                        types.Append($"{Attrs(dg.Attrs)}public delegate {r} {dg.Name}({string.Join(", ", inv.Params.Select(p => p.Type.Cs + " " + p.CsName))});\n");
                        break;
                    }
                case MethodDecl m: prog.Append(Method(m, binder.Program)); break;
                case ConstDecl c: prog.Append(Const(c, binder.Program)); break;
            }
        }
    }

    /// <summary>Attributes of a positional record parameter. They target the generated property (where serializers
    /// look) unless written with an explicit target (`@[param: X]`).</summary>
    static string ParamAttrs(TypeDecl d, string field)
    {
        var p = d.RecordParams.FirstOrDefault(r => r.Name == field);
        if (p == null || p.Attrs.Count == 0) return "";
        return string.Concat(p.Attrs.Select(a => System.Text.RegularExpressions.Regex.IsMatch(a, @"^\w+\s*:\s") ? $"[{a}] " : $"[property: {a}] "));
    }

    static string Attrs(List<string> attrs)
    {
        var sb = new StringBuilder();
        foreach (var a in attrs)
        {
            if (a is "Stack" or "Open" or "SoA" or "StrictMath" or "Native" || a.StartsWith("Native(") || a.StartsWith("__enumerable:")) continue;
            if (a == "Inline") sb.Append("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]\n");
            else if (a == "NoInline") sb.Append("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.NoInlining)]\n");
            else if (a == "Hot") sb.Append("[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization)]\n");
            else sb.Append('[').Append(a).Append("]\n");
        }
        return sb.ToString();
    }

    string Constraints(List<Constraint> cs)
    {
        var sb = new StringBuilder();
        foreach (var c in cs)
        {
            var parts = c.Keywords.Select(k => k == "new" ? "new()" : k).ToList();
            parts.AddRange(c.Types.Select(t => binder.ResolveType(t).Cs));
            parts = parts.OrderBy(x => x is "struct" or "class" or "unmanaged" or "notnull" ? 0 : x == "new()" ? 2 : 1).ToList();
            sb.Append(" where ").Append(c.Param).Append(" : ").Append(string.Join(", ", parts));
        }
        return sb.ToString();
    }

    string Type(TypeDecl d)
    {
        var s = (TypeSym)d.Sym!;
        if (s.Kind == "extension")
        {
            var ext = new StringBuilder();
            foreach (var m in d.Members.OfType<MethodDecl>()) ext.Append(Method(m, s));
            return $"public static partial class {s.Name}\n{{\n{ext}}}\n";
        }
        var body = new StringBuilder();
        foreach (var it in d.Members)
        {
            switch (it)
            {
                case AccessorDecl a: body.Append(Accessor(a, s)); break;
                case FieldDecl f:
                    {
                        var fs = (FieldSym)f.Sym!;
                        body.Append($"{Attrs(f.Attrs)}private {(fs.IsStatic ? "static " : "")}{fs.Type.Cs} {fs.CsName}{(f.Init != null ? " = " + Init(f.Init, s) : "")};\n");
                        break;
                    }
                case ConstDecl c: body.Append(Const(c, s)); break;
                case MethodDecl { IsTemplate: true }: break;
                case MethodDecl m: body.Append(Method(m, s)); break;
                case TypeDecl { RefineScope: not null }: break;   // emitted at file level, in its own namespace (EmitFile)
                case TypeDecl nested: body.Append(Type(nested)); break;
                case EnumDecl e: body.Append(Enum(e)); break;
            }
        }
        // Ruby-style fields introduced by `@x = value` (declared once, in the first declaration of the type)
        foreach (var f in s.Fields.Values.Where(f => f.Kind == "inferred").ToList())
        {
            body.Append($"private {Lowerer.TypeCs(f.Type)} {f.CsName};\n");
            f.Kind = "inferred-emitted";
        }
        // fields introduced by `def initialize(@x : T)` in this declaration
        foreach (var m in d.Members.OfType<MethodDecl>())
            foreach (var p in m.Params.Where(p => p.Auto))
                if (s.Fields.TryGetValue(p.Name, out var f) && f.Kind == "auto")
                {
                    body.Append($"private {f.Type.Cs} {f.CsName};\n");
                    f.Kind = "auto-emitted";
                }
        string self = s.Name + (s.TypeParams.Count > 0 ? "<" + string.Join(", ", s.TypeParams) + ">" : "");
        var ops = d.Members.OfType<MethodDecl>().Select(m => m.Name).ToHashSet();
        if (ops.Contains("==") && !ops.Contains("!=")) body.Append($"public static bool operator !=({self} a, {self} b) => !(a == b);\n");
        if (ops.Contains("<") && !ops.Contains(">")) body.Append($"public static bool operator >({self} a, {self} b) => b < a;\n");
        if (ops.Contains("<=") && !ops.Contains(">=")) body.Append($"public static bool operator >=({self} a, {self} b) => b <= a;\n");
        if (s.SoaStore != null) body.Append(SoAStore.Emit(s));
        // C# runs struct field initializers only through a declared constructor: give `Cfg.new` one
        if (d.Kind == "struct" && !d.Members.OfType<MethodDecl>().Any(m => m.Name == "initialize")
            && d.Members.Any(m => m is AccessorDecl { Init: not null } or FieldDecl { Init: not null }))
            body.Append($"public {s.Name}() {{ }}\n");
        // `class Trio < IEnumerable(Int32)` with a GetEnumerator iterator: C# also needs the non-generic bridge
        bool implementsEnumerable = s.EnumerableElem != null
            || s.Bases.Any(b => b.Clr is { IsGenericType: true } c && c.GetGenericTypeDefinition() == typeof(IEnumerable<>));
        if (implementsEnumerable && d.Members.OfType<MethodDecl>().Any(m => m.Name == "GetEnumerator")
            && !d.Members.OfType<MethodDecl>().Any(m => m.Name.Contains("IEnumerable.GetEnumerator")))
            body.Append("global::System.Collections.IEnumerator global::System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();\n");
        // leaf classes are sealed: the JIT devirtualizes and inlines calls and type checks get cheaper
        bool open = s.HasSubclass || d.IsAbstract || d.Attrs.Contains("Open");
        string head = d.Kind switch
        {
            "module" => "public static partial class",
            "interface" => "public partial interface",
            "struct" => s.IsStack ? "public ref partial struct" : "public partial struct",
            "record" => open ? "public partial record" : "public sealed partial record",
            "record struct" => "public readonly partial record struct",
            _ => d.IsAbstract ? "public abstract partial class" : open ? "public partial class" : "public sealed partial class",
        };
        string prm = d.RecordParams.Count > 0 ? "(" + string.Join(", ", s.FieldOrder.Select(f => ParamAttrs(d, f) + s.Fields[f].Type.Cs + " " + s.Fields[f].CsName)) + ")" : "";
        string bases = s.Bases.Count > 0 ? " : " + string.Join(", ", s.Bases.Select(b => b.Cs)) : "";
        string where = Constraints(d.Constraints);
        if (d.Kind.StartsWith("record") && body.Length == 0) return $"{Attrs(d.Attrs)}{head} {self}{prm}{bases}{where};\n";
        return $"{Attrs(d.Attrs)}{head} {self}{prm}{bases}{where}\n{{\n{body}}}\n";
    }

    string Init(Expr e, TypeSym owner)
    {
        lowerer.Type = owner;
        lowerer.Method = null;
        var tmp = lowerer.LowerBody(new List<Stmt> { new ExprStmt { Expr = e, Line = e.Line } }, Tail.Return, new List<LocalSym>(), e.Line);
        return Printer.E(((MReturn)tmp[^1]).Value!);
    }

    string Accessor(AccessorDecl a, TypeSym owner)
    {
        var f = (FieldSym)a.Sym!;
        string st = f.IsStatic ? "static " : "";
        if (a.Kind == "event") return $"{Attrs(a.Attrs)}{(owner.Kind == "interface" ? "" : "public ")}{st}event {f.Type.Cs} {f.CsName};\n";
        if (owner.Kind == "interface") return $"{f.Type.Cs} {f.CsName} {(a.Kind == "getter" ? "{ get; }" : "{ get; set; }")}\n";
        string acc = a.Kind switch { "getter" => "{ get; private set; }", "setter" => "{ private get; set; }", _ => "{ get; set; }" };
        string init = a.Init != null ? " = " + Init(a.Init, owner) + ";" : "";
        return $"{Attrs(a.Attrs.Select(FieldTarget).ToList())}public {st}{Lowerer.TypeCs(f.Type)} {f.CsName} {acc}{init}\n";
    }

    /// <summary>Attributes valid only on fields (struct layout, marshalling) go to an accessor's backing field.</summary>
    static string FieldTarget(string attr)
    {
        string name = attr.Split('(')[0].Split('.')[^1].Trim();
        return name is "FieldOffset" or "FieldOffsetAttribute" or "NonSerialized" or "ThreadStatic" or "MarshalAs" or "FixedBuffer" && !attr.Contains(':') ? "field: " + attr : attr;
    }

    string Const(ConstDecl c, TypeSym owner)
    {
        var f = (FieldSym)c.Sym!;
        return $"{Attrs(c.Attrs)}public static readonly {f.Type.Cs} {c.Name} = {Init(c.Value, owner)};\n";
    }

    string Enum(EnumDecl e)
    {
        if (e.IsAdt)
        {
            // Rust-style sum type: closed hierarchy of sealed records (value equality, pattern matching)
            var es = (TypeSym)e.Sym!;
            var v = new StringBuilder();
            foreach (var vs in es.Variants)
            {
                if (vs.FieldOrder.Count == 0)
                    v.Append($"    public sealed record {vs.Name} : {e.Name} {{ public static readonly {vs.Name} Value = new(); }}\n");
                else
                    v.Append($"    public sealed record {vs.Name}({string.Join(", ", vs.FieldOrder.Select(f => vs.Fields[f].Type.Cs + " " + vs.Fields[f].CsName))}) : {e.Name};\n");
            }
            return $"{Attrs(e.Attrs)}public abstract partial record {e.Name}\n{{\n    private {e.Name}() {{ }}\n{v}}}\n";
        }
        var items = new List<string>();
        for (int i = 0; i < e.Names.Count; i++)
            items.Add(e.Values[i] != null ? e.Names[i] + " = " + Init(e.Values[i]!, binder.Program) : e.Names[i]);
        string under = e.Underlying != null ? " : " + binder.ResolveType(e.Underlying).Cs : "";
        return $"{Attrs(e.Attrs)}public enum {e.Name}{under}\n{{\n{string.Join(",\n", items)}\n}}\n";
    }

    static bool BlittableCs(string cs) => cs is "bool" or "byte" or "sbyte" or "short" or "ushort" or "int" or "uint" or "long" or "ulong" or "float" or "double" or "nint" or "nuint" or "char";

    sealed record FfiArg(string Cs, string Raw, string Arg, string? Setup);

    /// <summary>
    /// How one `fun` parameter crosses: blittable numbers as is, Bool as a byte, String/String? as a UTF-8 C string
    /// (<see cref="Alice.Runtime.Utf8Arg"/>: stack buffer, NUL rejected), arrays of numbers pinned in place.
    /// Null when the type needs the runtime marshaller.
    /// </summary>
    static FfiArg? FfiParam(string cs, string name)
    {
        string id = name.TrimStart('@');   // `@base`: derived names must not carry the keyword escape
        if (cs == "bool") return new(cs, "byte", $"{name} ? (byte)1 : (byte)0", null);
        if (cs.StartsWith("delegate* unmanaged")) return new("global::Alice.Runtime.NativeFn", cs, $"({cs}){name}.Address", null);
        if (BlittableCs(cs) || cs.EndsWith('*')) return new(cs, cs, name, null);
        if (cs is "string" or "string?")
            return new(cs, "byte*", $"__u_{id}.Pointer", $"using var __u_{id} = new global::Alice.Runtime.Utf8Arg({name}, stackalloc byte[global::Alice.Runtime.Utf8Arg.StackBytes]);");
        if (cs.EndsWith("[]") && cs[..^2] is var el && BlittableCs(el) && el != "bool" || cs.EndsWith("[]?") && BlittableCs(cs[..^3]) && cs[..^3] != "bool")
        {
            string e = cs.TrimEnd('?')[..^2];
            return new(cs, e + "*", $"__p_{id}", $"fixed ({e}* __p_{id} = {name})");
        }
        return null;
    }

    /// <summary>`out ts : Timespec` / `ref e : Int32`: C gets a pointer to the caller's variable, pinned for the call.</summary>
    static FfiArg FfiByRef(string mod, string cs, string name)
    {
        string id = name.TrimStart('@');
        string init = mod == "out" ? $"{name} = default;\n    " : "";   // C# requires an out parameter assigned before its address is taken
        return new($"{mod} {cs}", cs + "*", $"__p_{id}", $"{init}fixed ({cs}* __p_{id} = &{name})");
    }

    /// <summary>Raw return type and a format turning the raw call `{0}` into the Alice value.</summary>
    static (string Raw, string Wrap)? FfiReturn(string cs, string fun) => cs switch
    {
        "void" => ("void", "{0}"),
        "bool" => ("byte", "{0} != 0"),
        "string?" => ("byte*", "global::Alice.Runtime.Utf8Arg.Decode({0})"),
        "string" => ("byte*", $"global::Alice.Runtime.Utf8Arg.DecodeNonNull({{0}}, \"{fun}\")"),
        _ when BlittableCs(cs) || cs.EndsWith('*') => (cs, "{0}"),
        _ => null,
    };

    static string Lib(LibDecl l)
    {
        var s = (TypeSym)l.Sym!;
        var sb = new StringBuilder();
        // Bool is a 1-byte C bool (not the 4-byte Win32 BOOL default); @[Fast] drops the GC transition (~20% per call).
        // Primitive signatures stay blittable: a bool crosses as a byte behind an inlined wrapper, so the call needs no
        // marshalling stub (3x faster per call, inlinable by the JIT, nothing generated at run time for AOT).
        const string U1 = "[global::System.Runtime.InteropServices.MarshalAs(global::System.Runtime.InteropServices.UnmanagedType.U1)]";
        const string Inline = "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]\n";
        foreach (var f in l.Funs)
        {
            var m = s.Methods[f.Name][0];
            string import = $"[global::System.Runtime.InteropServices.DllImport(\"{l.LibName}\", EntryPoint = \"{f.Entry}\", ExactSpelling = true)]\n"
                + (f.Attrs.Contains("Fast") ? "[global::System.Runtime.InteropServices.SuppressGCTransition]\n" : "");
            var parts = m.Params.Select(p => p.Mod != "" ? FfiByRef(p.Mod, p.Type.Cs, p.CsName) : FfiParam(p.Type.Cs, p.CsName)).ToList();
            string retCs = m.Ret.IsVoid ? "void" : m.Ret.Cs;
            var ret = FfiReturn(retCs, f.Name);
            if (parts.All(x => x != null) && ret != null)
            {
                string sig = string.Join(", ", m.Params.Select((p, i) => parts[i]!.Cs + " " + p.CsName));
                bool callbacks = m.Params.Any(p => p.Type.Cs.StartsWith("delegate* unmanaged"));
                if (parts.All(x => x!.Raw == x.Cs && x.Setup == null) && ret.Value.Raw == retCs && !callbacks)
                {
                    sb.Append(import).Append($"public static extern {retCs} {m.CsName}({sig});\n");   // already blittable
                    continue;
                }
                string raw = "__raw_" + m.CsName.TrimStart('@');
                sb.Append(import).Append($"private static extern {ret.Value.Raw} {raw}({string.Join(", ", m.Params.Select((p, i) => parts[i]!.Raw + " " + p.CsName))});\n");
                string call = string.Format(ret.Value.Wrap, $"{raw}({string.Join(", ", parts.Select(x => x!.Arg))})");
                var setup = parts.Where(x => x!.Setup != null).Select(x => x!.Setup).ToList();
                sb.Append(Inline);
                if (callbacks) setup.Add(null);   // forces a block body: the rethrow follows the call
                if (setup.Count == 0) sb.Append($"public static {retCs} {m.CsName}({sig}) => {call};\n");
                else
                {
                    // `using var` lines first, then one nested `fixed` block per pinned array around the call
                    var body = new StringBuilder();
                    foreach (var x in setup.Where(x => x != null && !x.Contains("fixed ("))) body.Append("    ").Append(x).Append('\n');
                    var pins = setup.Where(x => x != null && x.Contains("fixed (")).ToList();
                    foreach (var x in pins) body.Append("    ").Append(x).Append("\n    {\n");
                    if (callbacks)   // an exception raised in an Alice callback resurfaces here, after the C frames are gone
                        body.Append(retCs == "void" ? $"    {call};\n    global::Alice.Runtime.NativeCallback.Rethrow();\n"
                            : $"    var __r = {call};\n    global::Alice.Runtime.NativeCallback.Rethrow();\n    return __r;\n");
                    else body.Append($"    {(retCs == "void" ? "" : "return ")}{call};\n");
                    foreach (var _ in pins) body.Append("    }\n");
                    sb.Append($"public static {retCs} {m.CsName}({sig})\n{{\n{body}}}\n");
                }
                continue;
            }
            // other types (blittable structs, delegates): the runtime marshaller
            string ps = string.Join(", ", m.Params.Select(p => (p.Type.Cs == "bool" ? U1 + " " : "") + p.Type.Cs + " " + p.CsName));
            sb.Append(import);
            if (m.Ret.Cs == "bool") sb.Append("[return: global::System.Runtime.InteropServices.MarshalAs(global::System.Runtime.InteropServices.UnmanagedType.U1)]\n");
            sb.Append($"public static extern {retCs} {m.CsName}({ps});\n");
        }
        return $"public static unsafe partial class {l.Name}\n{{\n{sb}}}\n";
    }

    static readonly Dictionary<string, string> OpNames = new()
    {
        ["+"] = "op_Add",
        ["-"] = "op_Sub",
        ["*"] = "op_Mul",
        ["/"] = "op_Div",
        ["%"] = "op_Mod",
        ["=="] = "op_Eq",
        ["<=>"] = "op_Cmp",
        ["!="] = "op_Ne",
        ["<"] = "op_Lt",
        [">"] = "op_Gt",
        ["<="] = "op_Le",
        [">="] = "op_Ge",
    };

    string Method(MethodDecl d, TypeSym owner) => d.RuleName != null ? MethodCore(d, owner) + Prover(d) : MethodCore(d, owner);

    /// <summary>Largest rule domain `alice prove` enumerates: about a minute of pure calls across cores.</summary>
    const long MaxRuleCases = 1L << 32;

    /// <summary>
    /// `__prove_rule()`: every case of the rule's domain, outer variable in parallel. Returns the case count and the
    /// first counterexample in domain order (a `false` result or an exception), or null when the rule holds on every
    /// case. The first, not any: PROOF.al must not depend on thread timing.
    /// </summary>
    string Prover(MethodDecl d)
    {
        var m = (MethodSym)d.Sym!;
        double cases = d.Domains.Aggregate(1.0, (acc, x) => acc * x.Size);
        if (cases > MaxRuleCases)
            throw new CompileException($"{file}:{d.Line}:{Math.Max(1, d.Col)}: rule domain of `{d.RuleName}` has {cases:0} cases, more than the {MaxRuleCases} `alice prove` checks exhaustively; narrow the ranges");
        string Var(int i) => m.Params[i].CsName;
        string Ty(RuleDomain x) => x.IsBool ? "bool" : x.Lo < int.MinValue || x.Hi > int.MaxValue ? "long" : "int";
        string Loop(RuleDomain x, int i) => x.IsBool
            ? $"foreach (var {Var(i)} in new[] {{ false, true }})"
            : $"for ({Ty(x)} {Var(i)} = {x.Lo}; {Var(i)} <= {x.Hi}; {Var(i)}++)";
        string args = string.Join(", ", d.Domains.Select((_, i) => Var(i)));
        string show = string.Join(", ", d.Domains.Select((x, i) => $"{x.Name} = {{{Var(i)}}}"));
        // the first failure in domain order: inner variables run in order within one outer value, and Break() lets every
        // lower outer value finish, so the smallest failing outer value wins whatever thread reaches a failure first
        string fail(string msg) => $"lock (__gate) {{ if (__k < __first) {{ __first = __k; __cex = {msg}; }} }} __st.Break(); return;";
        string check = $"bool __ok; try {{ __ok = {m.CsName}({args}); }} catch (global::System.Exception __e) {{ {fail($"$\"{show}: raised {{__e.GetType().Name}}\"")} }}\nif (!__ok) {{ {fail($"$\"{show}\"")} }}";
        string body = check;
        for (int i = d.Domains.Count - 1; i >= 1; i--) body = Loop(d.Domains[i], i) + "\n{\n" + body + "\n}";
        var sb = new StringBuilder();
        sb.Append($"public static (long, string?) __prove_{d.RuleName}()\n{{\n    string? __cex = null;\n    long __first = long.MaxValue;\n    var __gate = new object();\n");
        if (d.Domains.Count == 0)
            sb.Append($"    try {{ if (!{m.CsName}()) __cex = \"(no variables)\"; }} catch (global::System.Exception __e) {{ __cex = \"raised \" + __e.GetType().Name; }}\n");
        else
        {
            var outer = d.Domains[0];
            string range = outer.IsBool ? "0, 2" : $"{outer.Lo}L, {outer.Hi}L + 1";
            string bind = outer.IsBool ? $"bool {Var(0)} = __k == 1;" : $"{Ty(outer)} {Var(0)} = ({Ty(outer)})__k;";
            sb.Append($"    global::System.Threading.Tasks.Parallel.For({range}, (__k, __st) =>\n    {{\n        {bind}\n{body}\n    }});\n");
        }
        sb.Append($"    return ({(long)cases}L, __cex);\n}}\n");
        return sb.ToString();
    }

    string MethodCore(MethodDecl d, TypeSym owner)
    {
        var m = (MethodSym)d.Sym!;
        if (CEmitter.IsNative(d)) return NativeMethod(d, owner, m);
        if (!m.HasInferredGenerics || !d.HasBody) return MethodVariant(d, owner, null);
        // Crystal-style: one typed specialization per call-site argument types; generic body only if still needed
        var sb = new StringBuilder();
        foreach (var inst in m.Instances.Values.Where(i => i.Seen))
        {
            binder.Rebind(d, owner, inst);
            sb.Append(MethodVariant(d, owner, inst));
        }
        if (m.NeedsGeneric || sb.Length == 0)
        {
            binder.Rebind(d, owner, null);
            sb.Append(MethodVariant(d, owner, null));
        }
        return sb.ToString();
    }

    /// <summary>
    /// @[Native]: C version (clang), a function pointer resolved at type init, and the managed body as fallback:
    ///   name(args) => fp != null ? fp(pinned args) : __managed_name(args)
    /// </summary>
    string NativeMethod(MethodDecl d, TypeSym owner, MethodSym m)
    {
        Native.Add(d, m, file);
        var cps = Native.Params(m, d);
        string ret = Lowerer.TypeCs(m.Ret);
        string fpType = (CEmitter.SkipsGcTransition(d) ? "delegate* unmanaged[SuppressGCTransition]<" : "delegate* unmanaged<") + string.Join(", ", cps.SelectMany(p => p.Array ? new[] { p.Type.Elem!.Cs + "*", "int" } : new[] { p.Type.Cs }).Append(ret)) + ">";
        string fp = "__np_" + m.CsName.TrimStart('@');
        string cs = m.CsName;
        m.CsName = "__managed_" + cs.TrimStart('@');
        string managed = MethodVariant(d, owner, null);
        m.CsName = cs;
        string plist = string.Join(", ", m.Params.Select(p => $"{p.Type.Cs} {p.CsName}"));
        string args = string.Join(", ", m.Params.Select(p => p.CsName));
        var call = new StringBuilder();
        foreach (var p in cps.Where(p => p.Array)) call.Append($"fixed ({p.Type.Elem!.Cs}* __p_{p.Name} = {p.Name}) ");
        string nativeArgs = string.Join(", ", cps.SelectMany(p => p.Array ? new[] { "__p_" + p.Name, p.Name + ".Length" } : new[] { p.Name }));
        string invoke = ret == "void" ? $"{{ {fp}({nativeArgs}); return; }}" : $"return {fp}({nativeArgs});";
        var w = new StringBuilder();
        w.Append($"private static readonly unsafe {fpType} {fp} = ({fpType})global::Alice.Runtime.NativeLibs.Export(\"{NativeLib}\", \"{CEmitter.Symbol(m)}\");\n");
        w.Append($"#line {d.Line} \"{file}\"\n");
        w.Append($"public static unsafe {ret} {cs}({plist})\n{{\n");
        var arrNames = cps.Where(p => p.Array).Select(p => p.Name).ToList();
        string distinct = string.Concat(arrNames.SelectMany((a, i) => arrNames.Skip(i + 1).Select(b => $" && !ReferenceEquals({a}, {b})")));
        w.Append($"    if ({fp} != null{distinct})\n    {{\n        {call}{invoke}\n    }}\n");
        w.Append($"    {(ret == "void" ? "" : "return ")}__managed_{cs.TrimStart('@')}({args});\n}}\n");
        w.Append(managed);
        return w.ToString();
    }

    const string Hot = "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveOptimization)]\n";

    /// <summary>
    /// A self-recursive static function over primitives and primitive arrays, returning one of them, is a compute kernel: fully optimized
    /// from its first call instead of spending its hottest frames in tier 0 and OSR. With no reference parameters it
    /// has no virtual call sites, so tiered PGO has nothing to devirtualize.
    /// </summary>
    static bool Kernel(MethodDecl d, MethodSym m, Instance? inst, List<MStmt> body)
    {
        var ret = inst?.Ret ?? m.Ret;
        if (!(ret.IsVoid || Primitive(ret) || ret.Kind == "array" && ret.Elem != null && Primitive(ret.Elem))) return false;   // object-building recursion gains from tier-1 PGO
        if (!m.IsStatic || m.IsAsync || m.IsCtor || d.Attrs.Any(a => a is "Hot" or "Inline" or "NoInline")) return false;
        for (int i = 0; i < m.Params.Count; i++)
        {
            var t = inst != null ? inst.Args[i] : m.Params[i].Type;
            if (!(Primitive(t) || t.Kind == "array" && t.Elem != null && Primitive(t.Elem))) return false;
        }
        return MirFacts.Calls(body, m.CsName);
    }

    /// <summary>
    /// A loop inside a loop: the method usually runs long from a single call, so tier 0 with PGO instrumentation
    /// runs it until on-stack replacement (suite nbody: 151 ms -> 78 ms, C# 78 ms). Compiled fully optimized instead;
    /// steady-state benchmarks measured within noise.
    /// </summary>
    static bool LoopNest(List<MStmt> body, int depth) => body.Any(s => s switch
    {
        MFor f => depth >= 1 || LoopNest(f.Body, depth + 1),
        MWhile w => depth >= 1 || LoopNest(w.Body, depth + 1),
        MForeach fe => depth >= 1 || LoopNest(fe.Body, depth + 1),
        MIf i => LoopNest(i.Then, depth) || (i.Else != null && LoopNest(i.Else, depth)),
        MBlock b => LoopNest(b.Body, depth),
        _ => false,
    });

    HashSet<MethodSym>? loopLeaves;

    /// <summary>
    /// Static functions over primitives (parameters and result) that loops call, directly or through another such
    /// function: `noise(x, y)` in a pixel loop, `lattice` inside it. Short programs end before tiering promotes them,
    /// and with no reference values there is nothing for PGO to devirtualize, so they compile fully optimized at once.
    /// </summary>
    HashSet<MethodSym> LoopLeaves()
    {
        if (loopLeaves != null) return loopLeaves;
        static bool Leaf(MethodSym m) => m.IsStatic && !m.IsAsync && !m.IsCtor && !m.UsesYield && m.Decl is { HasBody: true } d
            && !d.Attrs.Any(a => a is "Hot" or "Inline" or "NoInline") && m.TypeParams.Count == 0 && !m.HasInferredGenerics
            && (m.Ret.IsVoid || Primitive(m.Ret)) && m.Params.All(p => Primitive(p.Type));
        static IEnumerable<MethodSym> Calls(IEnumerable<Expr> es) => es.Select(e => e switch
        {
            CallExpr { Sym: MethodSym c } => c,
            NameExpr { Res: "call", Sym: MethodSym c } => c,
            _ => null,
        }).OfType<MethodSym>();
        var bodies = new List<List<Stmt>>();
        void Collect(IEnumerable<Item> items)
        {
            foreach (var it in items)
                switch (it)
                {
                    case NamespaceItem ns: Collect(ns.Items); break;
                    case TypeDecl td: Collect(td.Members); break;
                    case MethodDecl md when md.HasBody: bodies.Add(md.Body); break;
                    case StmtItem si: bodies.Add([si.Stmt]); break;
                }
        }
        foreach (var f in binder.Files) Collect(f.Items);
        var set = new HashSet<MethodSym>();
        foreach (var b in bodies)
            foreach (var loop in Lowerer.WalkStmts(b))
                if (loop is ForStmt or WhileStmt)
                    foreach (var c in Calls(Lowerer.Walk(loop is ForStmt fs ? fs.Body : ((WhileStmt)loop).Body)))
                        if (Leaf(c)) set.Add(c);
        var work = new Queue<MethodSym>(set);
        while (work.TryDequeue(out var m))
            foreach (var c in Calls(Lowerer.Walk(m.Decl!.Body)))
                if (Leaf(c) && set.Add(c)) work.Enqueue(c);
        return loopLeaves = set;
    }

    static bool Primitive(AType t) => t.Kind == "prim" && !t.Nullable && t.Cs != "decimal";

    string MethodVariant(MethodDecl d, TypeSym owner, Instance? inst)
    {
        var m = (MethodSym)d.Sym!;
        string dir = $"#line {d.Line} \"{file}\"\n";
        AType retT = inst?.Ret ?? m.Ret;
        if (inst != null && retT.IsUnknown) retT = AType.Dynamic;
        string ret = Lowerer.TypeCs(retT);
        string asyncKw = "";
        if (m.IsAsync) asyncKw = "async ";
        if (m.IsAsync && !m.IsIterator)   // an async iterator returns IAsyncEnumerable itself, not a Task of it
        {
            ret = retT.IsVoid ? "global::System.Threading.Tasks.Task" : $"global::System.Threading.Tasks.Task<{ret}>";
        }
        var tps = inst == null ? m.TypeParams : m.TypeParams.Where(tp => !m.Params.Any(p => p.Inferred && p.Type.Cs == tp)).ToList();
        string gen = tps.Count > 0 ? "<" + string.Join(", ", tps) + ">" : "";
        var ps = new List<string>();
        if (owner.Kind == "extension") ps.Add($"this {owner.ExtTarget!.Cs} self");
        for (int i = 0; i < m.Params.Count; i++)
        {
            var p = m.Params[i];
            var pt = inst != null ? inst.Args[i] : p.Type;
            string def = d.Params[i].Default != null ? " = " + Init(d.Params[i].Default!, owner) : "";
            ps.Add(p.Splat ? $"params {pt.Cs}[] {p.CsName}" : $"{pt.Cs} {p.CsName}{def}");
        }
        string plist = string.Join(", ", ps);
        string where = Constraints(d.Constraints);
        if (owner.Kind == "interface" && !d.HasBody) return $"{dir}{ret} {m.CsName}{gen}({plist}){where};\n";
        if (d.IsAbstract) return $"{dir}{d.Vis} abstract {ret} {m.CsName}{gen}({plist}){where};\n";
        if (d.IsPartial)   // the generator supplies the body; the declaration carries the attributes it reads
            return $"{dir}{Attrs(d.Attrs)}{d.Vis}{(m.IsStatic || owner.Kind is "module" or "program" ? " static" : "")} partial {ret} {m.CsName}{gen}({plist}){where};\n";

        lowerer.Type = owner;
        lowerer.Method = m;
        bool returns = !retT.IsVoid && !m.IsCtor && !m.IsIterator;
        bool plain = !m.IsCtor && !(d.Name == "to_s" && m.Params.Count == 0) && d.Name != "[]" && !OpNames.ContainsKey(d.Name);
        lowerer.CloneOk = plain && Virtual(m, owner, d.Vis).Mod == "";
        lowerer.Forked = false;
        var body = lowerer.LowerBody(d.Body, returns ? Tail.Return : Tail.None, d.HoistedLocals, d.Line);
        string code = Print(body, 1);
        string extra = string.Concat(lowerer.Extra);
        lowerer.Extra.Clear();
        if (lowerer.Forked) extra += SerialClone(d, m, owner, ret, ps, returns);
        lowerer.CloneOk = false;
        string attrs = extra + Attrs(d.Attrs) + (Kernel(d, m, inst, body) || LoopLeaves().Contains(m) || !d.Attrs.Any(x => x is "Hot" or "Inline" or "NoInline") && LoopNest(body, 0) ? Hot : "");
        if (m.IsCtor)
        {
            string baseInit = "";
            if (d.SuperInit != null)
            {
                lowerer.Type = owner;
                baseInit = " : base(" + string.Join(", ", d.SuperInit.Select(a => Init(a.Value!, owner))) + ")";
            }
            var autos = new StringBuilder();
            foreach (var p in m.Params.Where(p => p.Auto)) autos.Append($"    this.{Binder.Mangle(p.Name)} = {p.CsName};\n");
            return $"{attrs}{dir}{d.Vis} {owner.Name}({plist}){baseInit}\n{{\n{autos}{code}}}\n";
        }
        if (d.Name == "to_s" && m.Params.Count == 0) return $"{attrs}{dir}public override string ToString()\n{{\n{code}}}\n";
        if (d.Name == "[]") return $"{attrs}{dir}public {ret} this[{plist}]\n{{\nget\n{{\n{code}}}\n}}\n";
        if (OpNames.TryGetValue(d.Name, out var opName))
        {
            string self = owner.Name + (owner.TypeParams.Count > 0 ? "<" + string.Join(", ", owner.TypeParams) + ">" : "");
            string args = string.Join(", ", m.Params.Select(p => p.CsName));
            string op = d.Name == "<=>" ? "" : $"public static {ret} operator {d.Name}({self} self, {plist}) => self.{opName}({args});\n";   // C# has no <=> operator
            return $"{attrs}{dir}public {ret} {opName}({plist})\n{{\n{code}}}\n{op}";
        }
        var (vis, virt) = Virtual(m, owner, d.Vis);
        string mods = vis + (m.IsStatic || owner.Kind == "extension" ? " static" : "") + virt + (asyncKw != "" ? " async" : "") + (d.IsUnsafe ? " unsafe" : "");
        return $"{attrs}{dir}{mods} {ret} {m.CsName}{gen}({plist}){where}\n{{\n{code}}}\n";
    }

    /// <summary>`m__serial`: the method lowered again with no forks, self-calls staying in the clone.</summary>
    string SerialClone(MethodDecl d, MethodSym m, TypeSym owner, string ret, List<string> ps, bool returns)
    {
        lowerer.SerialClone = true;
        lowerer.Forked = false;
        try
        {
            var body = lowerer.LowerBody(d.Body, returns ? Tail.Return : Tail.None, d.HoistedLocals, d.Line);
            string code = Print(body, 1);
            string extra = string.Concat(lowerer.Extra);
            lowerer.Extra.Clear();
            var plist = string.Join(", ", ps.Select(p => p.IndexOf(" = ", StringComparison.Ordinal) is int k and >= 0 ? p[..k] : p));
            string mods = "private" + (m.IsStatic || owner.Kind == "extension" ? " static" : "") + (d.IsUnsafe ? " unsafe" : "");
            return $"{extra}{mods} {ret} {m.CsName}{Lowering.Lowerer.SerialSuffix}({plist})\n{{\n{code}}}\n";
        }
        finally { lowerer.SerialClone = false; }
    }

    /// <summary>Alice dispatch is virtual only where the program needs it, so the JIT can devirtualize/inline the rest.</summary>
    static (string Vis, string Mod) Virtual(MethodSym m, TypeSym owner, string vis)
    {
        if (m.IsStatic || owner.Kind != "class" || vis == "private") return (vis, "");
        for (var b = owner.BaseClass; b != null; b = b.BaseClass)
            if (b.Methods.ContainsKey(m.Name)) return (vis, " override");
        // overriding a .NET virtual: keep the base accessibility (e.g. MonoGame's protected Update/Draw)
        for (var s = owner; s != null; s = s.BaseClass)
            foreach (var b in s.Bases)
            {
                if (b.Clr == null || b.Clr.IsInterface) continue;
                foreach (var bm in b.Clr.GetMethods(System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.NonPublic))
                    if (bm.Name == m.CsName && bm.IsVirtual && !bm.IsFinal && bm.GetParameters().Length == m.Params.Count && !bm.IsPrivate && !bm.IsAssembly)
                        return (bm.IsPublic ? "public" : "protected", " override");
            }
        return (vis, owner.HasSubclass ? " virtual" : "");
    }
