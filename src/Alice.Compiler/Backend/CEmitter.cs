using System.Text;
using Alice.Compiler.Semantics;
using Alice.Compiler.Syntax;

namespace Alice.Compiler.Backend;

/// <summary>
/// `@[Native]` functions -> C (compiled by clang -O3 -march=native into a shared library). Supported subset:
/// numbers, Bool, Array(number) parameters (passed as pointer + length), locals, if/while/for ranges, Math.*,
/// and calls to other native functions. Anything else is a compile error naming the construct.
///
/// The C keeps Alice's safety rules (memory-safety.md, ADR 0013): every array access is bounds-checked, integer
/// `+ - *` (and `/ %` by zero or MIN / -1) trap on overflow, shift counts are masked like C#. A violation prints the
/// error and aborts the process: native code has no exception to raise, and it must never read or write out of bounds.
/// </summary>
public sealed class CEmitter
{
    readonly StringBuilder decls = new();
    readonly StringBuilder defs = new();
    string file = "";
    MethodSym current = null!;

    public bool IsEmpty => defs.Length == 0;

    public string Source =>
        "/* generated by alice from @[Native] functions */\n#include <math.h>\n#include <stdint.h>\n#include <stdbool.h>\n#include <stdlib.h>\n#include <stdio.h>\n" +
        Runtime + "#define ALICE_EXPORT __attribute__((visibility(\"default\")))\n\n" + decls + "\n" + defs;

    /// <summary>Checked helpers: Alice's semantics in C (floored / and %, trapping overflow and bounds).</summary>
    static readonly string Runtime = BuildRuntime();

    static string BuildRuntime()
    {
        var o = new StringBuilder();
        o.Append("__attribute__((noreturn, cold, noinline)) static void alice_trap(const char* what) { fprintf(stderr, \"alice @[Native]: %s\\n\", what); fflush(stderr); abort(); }\n");
        o.Append("static inline int64_t alice_ix(int64_t i, int64_t n) { if (__builtin_expect((uint64_t)i >= (uint64_t)n, 0)) alice_trap(\"index out of range\"); return i; }\n");
        foreach (var (sfx, t, min) in new[] { ("i32", "int32_t", "INT32_MIN"), ("i64", "int64_t", "INT64_MIN"), ("u32", "uint32_t", ""), ("u64", "uint64_t", "") })
        {
            foreach (var op in new[] { "add", "sub", "mul" })
                o.Append($"static inline {t} alice_{op}_{sfx}({t} a, {t} b) {{ {t} r; if (__builtin_{op}_overflow(a, b, &r)) alice_trap(\"arithmetic overflow\"); return r; }}\n");
            string zero = "if (b == 0) alice_trap(\"division by zero\");";
            if (min != "")
            {
                // Alice semantics: signed / and % are floored (the sign of % follows the divisor); MIN / -1 overflows
                o.Append($"static inline {t} alice_fdiv_{sfx}({t} a, {t} b) {{ {zero} if (a == {min} && b == -1) alice_trap(\"arithmetic overflow\"); {t} q = a / b; return (a % b != 0 && ((a ^ b) < 0)) ? q - 1 : q; }}\n");
                o.Append($"static inline {t} alice_imod_{sfx}({t} a, {t} b) {{ {zero} if (a == {min} && b == -1) alice_trap(\"arithmetic overflow\"); {t} r = a % b; return (r != 0 && ((r ^ b) < 0)) ? r + b : r; }}\n");
            }
            else
            {
                o.Append($"static inline {t} alice_fdiv_{sfx}({t} a, {t} b) {{ {zero} return a / b; }}\n");
                o.Append($"static inline {t} alice_imod_{sfx}({t} a, {t} b) {{ {zero} return a % b; }}\n");
            }
        }
        o.Append("static inline double alice_fmod(double a, double b) { double r = fmod(a, b); return (r != 0 && ((r < 0) != (b < 0))) ? r + b : r; }\n");
        return o.ToString();
    }

    /// <summary>Suffix of the checked helpers for an integer C# type, null for anything else.</summary>
    static string? IntSuffix(string cs) => cs switch { "int" => "i32", "long" => "i64", "uint" => "u32", "ulong" => "u64", _ => null };

    /// <summary>`l op r` with Alice's semantics for a result of C# type cs (also the compound assignments).</summary>
    string Bin(Node at, string op, string cs, string l, string r)
    {
        string? ix = IntSuffix(cs);
        string? ct = CTypeCs(cs);
        return op switch
        {
            "**" => $"pow((double)({l}), (double)({r}))",
            "%" when cs is "double" or "float" => $"alice_fmod({l}, {r})",
            "+" when ix != null => $"alice_add_{ix}({l}, {r})",
            "-" when ix != null => $"alice_sub_{ix}({l}, {r})",
            "*" when ix != null => $"alice_mul_{ix}({l}, {r})",
            "/" when ix != null => $"alice_fdiv_{ix}({l}, {r})",
            "%" when ix != null => $"alice_imod_{ix}({l}, {r})",
            // C# masks the shift count; a left shift of a negative signed value is undefined in C: shift the bits unsigned
            "<<" when ix != null => $"(({ct})((u{(ct!.StartsWith('u') ? ct[1..] : ct)})({l}) << (({r}) & {(ix.EndsWith("32") ? 31 : 63)})))",
            ">>" when ix != null => $"(({l}) >> (({r}) & {(ix.EndsWith("32") ? 31 : 63)}))",
            "+" or "-" or "*" or "/" when cs is "double" or "float" => $"({l} {op} {r})",
            "==" or "!=" or "<" or ">" or "<=" or ">=" or "&&" or "||" or "&" or "|" or "^" => $"({l} {op} {r})",
            _ => throw Unsupported(at, $"operator {op} on {cs}"),
        };
    }

    public static string? CType(AType t) => CTypeCs(t.Cs);

    static string? CTypeCs(string cs) => cs switch
    {
        "double" => "double",
        "float" => "float",
        "int" => "int32_t",
        "long" => "int64_t",
        "short" => "int16_t",
        "byte" => "uint8_t",
        "sbyte" => "int8_t",
        "uint" => "uint32_t",
        "ulong" => "uint64_t",
        "bool" => "bool",
        "void" => "void",
        _ => null,
    };

    public static bool IsNative(MethodDecl d) => d.Attrs.Any(a => a == "Native" || a.StartsWith("Native("));

    /// <summary>
    /// Safe to call without a GC transition: straight-line code (no loops, no calls to other native functions),
    /// so it is short and never blocks or calls back. `@[Native(fast)]` asserts it for loop functions.
    /// </summary>
    public static bool SkipsGcTransition(MethodDecl d) =>
        d.Attrs.Contains("Native(fast)") || !AstWalk_HasLoopOrNativeCall(d);

    static bool AstWalk_HasLoopOrNativeCall(MethodDecl d)
    {
        bool found = false;
        AstWalk.Each(d.Body, n =>
        {
            if (n is WhileStmt or ForStmt) found = true;
            if (n is CallExpr { Sym: MethodSym { Decl: { } md } } && IsNative(md)) found = true;
        });
        return found;
    }

    CompileException Unsupported(Node n, string what) => new($"{file}:{n.Line}:{Math.Max(1, n.Col)}: @[Native] {current.Name}: {what} is not supported in native code (use plain Alice for it)");

    public static string Symbol(MethodSym m) => "alice_" + m.CsName.TrimStart('@');

    /// <summary>C parameter list; arrays become `T* name, int32_t name__len`.</summary>
    public List<(string CType, string Name, bool Array, AType Type)> Params(MethodSym m, Node at)
    {
        var r = new List<(string, string, bool, AType)>();
        foreach (var p in m.Params)
        {
            if (p.Type.Kind == "array" && p.Type.Elem != null && CType(p.Type.Elem) is string et && et != "bool")
                r.Add((et + "*", p.CsName.TrimStart('@'), true, p.Type));
            else if (CType(p.Type) is string ct && ct != "void") r.Add((ct, p.CsName.TrimStart('@'), false, p.Type));
            else throw Unsupported(at, $"parameter type {p.Type.Cs}");
        }
        return r;
    }

    public void Add(MethodDecl d, MethodSym m, string fileName)
    {
        file = fileName;
        current = m;
        if (!m.IsStatic) throw Unsupported(d, "an instance method (use a top-level def or `def self.`)");
        string ret = CType(m.Ret) ?? throw Unsupported(d, $"return type {m.Ret.Cs}");
        var ps = Params(m, d);
        string plist = string.Join(", ", ps.Select(p => p.Array ? $"{p.CType} {p.Name}, int32_t {p.Name}__len" : $"{p.CType} {p.Name}"));
        string sig = $"ALICE_EXPORT {ret} {Symbol(m)}({plist})";
        decls.Append(sig).Append(";\n");
        var body = new StringBuilder();
        foreach (var h in d.HoistedLocals) body.Append($"    {LocalType(h, d)} {Name(h)} = 0;\n");
        Block(body, d.Body, 1, ret != "void");
        var arrays = ps.Where(p => p.Array).ToList();
        if (arrays.Count == 0)
        {
            defs.Append(sig).Append("\n{\n").Append(body).Append("}\n\n");
            return;
        }
        // Small-data specialization (what makes hand-written C fast): the worker is compiled once per small length
        // of the first array (a compile-time constant, so loops fully unroll), on stack copies of the arrays
        // (no aliasing; values stay in registers). Larger inputs use the generic worker in place.
        string impl = Symbol(m) + "__impl";
        string driver = arrays[0].Name;
        // whole identifiers only: `a__len` must not rewrite `ba__len`
        string implBody = Alice.Core.Text.Regex.Cached($@"(?<![A-Za-z0-9_]){Alice.Core.Text.Regex.Escape(driver)}__len(?![A-Za-z0-9_])").Replace(body.ToString(), "alice__N");
        defs.Append($"static inline __attribute__((always_inline)) {ret} {impl}({plist}, const int32_t alice__N)\n{{\n{implBody}}}\n\n");
        var written = WrittenArrays(d.Body);
        string args(Func<(string CType, string Name, bool Array, AType Type), string> arr) =>
            string.Join(", ", ps.Select(p => p.Array ? $"{arr(p)}, {p.Name}__len" : p.Name));
        var o = new StringBuilder();
        o.Append(sig).Append("\n{\n");
        o.Append($"    if ({string.Join(" && ", arrays.Select(a => $"{a.Name}__len <= {SmallLimit}"))})\n    {{\n");
        foreach (var a in arrays)
        {
            string et = a.CType.TrimEnd('*');
            o.Append($"        {et} alice__s_{a.Name}[{SmallLimit}];\n        for (int32_t alice__k = 0; alice__k < {a.Name}__len; alice__k++) alice__s_{a.Name}[alice__k] = {a.Name}[alice__k];\n");
        }
        if (ret != "void") o.Append($"        {ret} alice__r = 0;\n");
        o.Append($"        switch ({driver}__len)\n        {{\n");
        for (int k = 0; k <= SmallLimit; k++)
            o.Append($"            case {k}: {(ret != "void" ? "alice__r = " : "")}{impl}({args(a => "alice__s_" + a.Name)}, {k}); break;\n");
        o.Append("        }\n");
        foreach (var a in arrays.Where(a => written.Contains(a.Name)))
            o.Append($"        for (int32_t alice__k = 0; alice__k < {a.Name}__len; alice__k++) {a.Name}[alice__k] = alice__s_{a.Name}[alice__k];\n");
        o.Append(ret != "void" ? "        return alice__r;\n" : "        return;\n");
        o.Append("    }\n");
        o.Append($"    {(ret != "void" ? "return " : "")}{impl}({args(a => a.Name)}, {driver}__len);\n}}\n\n");
        defs.Append(o);
    }

    const int SmallLimit = 64;

    /// <summary>Array parameters the function writes (copied back after the small-data path).</summary>
    static HashSet<string> WrittenArrays(List<Stmt> body)
    {
        var r = new HashSet<string>();
        void Walk(List<Stmt> b)
        {
            foreach (var s in b)
            {
                if (s is Assign { Target: IndexExpr { Target: NameExpr { Sym: LocalSym l } } }) r.Add(l.CsName.TrimStart('@'));
                switch (s)
                {
                    case IfStmt i: foreach (var x in i.Bodies) Walk(x); if (i.Else != null) Walk(i.Else); break;
                    case WhileStmt w: Walk(w.Body); break;
                    case ForStmt f: Walk(f.Body); break;
                }
            }
        }
        Walk(body);
        return r;
    }

    string LocalType(LocalSym l, Node at) => CType(l.Type) is string t && t != "void" ? t : throw Unsupported(at, $"local '{l.Name}' of type {l.Type.Cs}");

    static string Name(LocalSym l) => "l_" + l.CsName.TrimStart('@');

    static string Pad(int ind) => new(' ', ind * 4);

    void Block(StringBuilder o, List<Stmt> body, int ind, bool tailReturns)
    {
        for (int i = 0; i < body.Count; i++) Stmt(o, body[i], ind, tailReturns && i == body.Count - 1);
    }

    void Stmt(StringBuilder o, Stmt s, int ind, bool tail)
    {
        string pad = Pad(ind);
        switch (s)
        {
            case ExprStmt es:
                o.Append(pad).Append(tail && !es.Expr.Type.IsVoid ? "return " : "").Append(E(es.Expr)).Append(";\n");
                break;
            case Assign { Declares: { } d } a:
                o.Append(pad).Append($"{LocalType(d, a)} {Name(d)} = {E(a.Value)};\n");
                break;
            case Assign a:
                if (a.Op is "**=" or "||=" or "&&=") throw Unsupported(a, $"operator {a.Op}");
                if (a.Op == "=") { o.Append(pad).Append($"{E(a.Target)} = {E(a.Value)};\n"); break; }
                {
                    // `t op= v` is `t = t op v` with the checked operator; an element is addressed (and bounds-checked) once
                    string op = a.Op[..^1], cs = a.Target.Type.Cs;
                    if (a.Target is IndexExpr)
                        o.Append(pad).Append($"{{ {CType(a.Target.Type) ?? throw Unsupported(a, $"element type {cs}")}* alice__p = &{E(a.Target)}; *alice__p = {Bin(a, op, cs, "*alice__p", E(a.Value))}; }}\n");
                    else
                    {
                        string t = E(a.Target);
                        o.Append(pad).Append($"{t} = {Bin(a, op, cs, t, E(a.Value))};\n");
                    }
                }
                break;
            case LocalDecl ld:
                o.Append(pad).Append($"{LocalType(ld.Local!, ld)} {Name(ld.Local!)} = {(ld.Value != null ? E(ld.Value) : "0")};\n");
                break;
            case IfStmt i:
                for (int k = 0; k < i.Conds.Count; k++)
                {
                    o.Append(pad).Append(k == 0 ? "if (" : "else if (").Append(E(i.Conds[k])).Append(")\n").Append(pad).Append("{\n");
                    Block(o, i.Bodies[k], ind + 1, tail);
                    o.Append(pad).Append("}\n");
                }
                if (i.Else != null)
                {
                    o.Append(pad).Append("else\n").Append(pad).Append("{\n");
                    Block(o, i.Else, ind + 1, tail);
                    o.Append(pad).Append("}\n");
                }
                break;
            case WhileStmt w:
                o.Append(pad).Append($"while ({E(w.Cond)})\n").Append(pad).Append("{\n");
                Block(o, w.Body, ind + 1, false);
                o.Append(pad).Append("}\n");
                break;
            case ForStmt f when f.Iter is RangeExpr r && f.Locals.Count == 1:
                {
                    string v = Name(f.Locals[0]);
                    // `a...b`: v < b <= MAX before the step, so `v++` cannot overflow (and stays a plain induction variable the
                    // optimizer can unroll); `a..MAX` or a body that moves v steps checked and traps instead of wrapping
                    bool plain = r.Excl && !Lowering.Lowerer.WalkStmts(f.Body).Any(x => x is Assign { Target: NameExpr { Sym: LocalSym c } } && c == f.Locals[0]);
                    string step = !plain && IntSuffix(f.Locals[0].Type.Cs) is { } sx ? $"{v} = alice_add_{sx}({v}, 1)" : $"{v}++";
                    o.Append(pad).Append($"for ({LocalType(f.Locals[0], f)} {v} = {E(r.A)}; {v} {(r.Excl ? "<" : "<=")} {E(r.B)}; {step})\n").Append(pad).Append("{\n");
                    Block(o, f.Body, ind + 1, false);
                    o.Append(pad).Append("}\n");
                    break;
                }
            case ReturnStmt rs:
                o.Append(pad).Append(rs.Value != null ? $"return {E(rs.Value)};\n" : "return;\n");
                break;
            case BreakStmt:
                o.Append(pad).Append("break;\n");
                break;
            case NextStmt { Value: null }:
                o.Append(pad).Append("continue;\n");
                break;
            default:
                throw Unsupported(s, s.GetType().Name.Replace("Stmt", "").ToLowerInvariant() + " statements");
        }
    }

    static readonly Dictionary<string, string> MathFns = new()
    {
        ["Sqrt"] = "sqrt",
        ["Sin"] = "sin",
        ["Cos"] = "cos",
        ["Tan"] = "tan",
        ["Exp"] = "exp",
        ["Log"] = "log",
        ["Log10"] = "log10",
        ["Pow"] = "pow",
        ["Floor"] = "floor",
        ["Ceiling"] = "ceil",
        ["Round"] = "nearbyint",
        ["Atan"] = "atan",
        ["Atan2"] = "atan2",
        ["Asin"] = "asin",
        ["Acos"] = "acos",
        ["Sinh"] = "sinh",
        ["Cosh"] = "cosh",
        ["Tanh"] = "tanh",
        ["Cbrt"] = "cbrt",
    };

    string E(Expr e)
    {
        switch (e)
        {
            case LitExpr { Kind: "int" } l:
                return l.Text.EndsWith("L") ? l.Text[..^1] + "LL" : l.Text;
            case LitExpr { Kind: "float" } l:
                return l.Text.EndsWith("d") ? l.Text[..^1] : l.Text;
            case LitExpr { Kind: "bool" } l:
                return l.Text;
            case NameExpr { Res: "local", Sym: LocalSym l }:
                return current.Params.Any(p => p.CsName == l.CsName) ? l.CsName.TrimStart('@') : Name(l);
            case NameExpr { Res: "call", Sym: MethodSym m } when m.Decl != null && IsNative(m.Decl):
                return $"{Symbol(m)}()";
            case CallExpr { Res: "ext", Recv: NameExpr { Sym: LocalSym arr, Type.Kind: "array" } } c when Binder.Mangle(c.Name) is "size" or "length":
                return arr.CsName.TrimStart('@') + "__len";
            case IndexExpr { Target: NameExpr { Sym: LocalSym arr, Type.Kind: "array" } } ix when ix.Args.Count == 1:
                {
                    string a = arr.CsName.TrimStart('@');
                    return $"{a}[alice_ix({E(ix.Args[0].Value!)}, {a}__len)]";
                }
            case BinaryExpr b:
                // comparisons and logic take the operand type; arithmetic the result type
                return Bin(b, b.Op, b.Op is "<<" or ">>" ? b.L.Type.Cs : b.Type.Cs, E(b.L), E(b.R));
            case UnaryExpr { Op: "-" } u when IntSuffix(u.Type.Cs) is { } us:
                return $"alice_sub_{us}(0, {E(u.E)})";   // -MIN overflows
            case UnaryExpr { Op: "-" or "!" or "~" } u:
                return $"({u.Op}{E(u.E)})";
            case TernaryExpr t:
                return $"({E(t.C)} ? {E(t.A)} : {E(t.B)})";
            case CallExpr mc when mc is { Res: "clr", Recv: ConstExpr, Sym: System.Reflection.MethodInfo { DeclaringType.FullName: "System.Math" } }:
                {
                    var args = mc.Args.Select(a => E(a.Value!)).ToList();
                    if (mc.Name == "Abs") return mc.Type.Cs is "double" or "float" ? $"fabs({args[0]})" : $"llabs({args[0]})";
                    if (mc.Name is "Min" or "Max")
                        return mc.Type.Cs is "double" or "float" ? $"f{mc.Name.ToLowerInvariant()}({args[0]}, {args[1]})" : $"(({args[0]}) {(mc.Name == "Min" ? "<" : ">")} ({args[1]}) ? ({args[0]}) : ({args[1]}))";
                    if (MathFns.TryGetValue(mc.Name, out var fn)) return $"{fn}({string.Join(", ", args)})";
                    throw Unsupported(mc, $"Math.{mc.Name}");
                }
            case ConstExpr { Res: "path", Sym: ConstPath { Owner.Clr: { } oc, Members: [(string member, false)] } } when oc == typeof(Math):
                return member switch { "PI" => "3.14159265358979323846", "E" => "2.71828182845904523536", _ => throw Unsupported(e, $"Math.{member}") };
            case CallExpr { Res: "alice", Sym: MethodSym m } c when m.Decl != null && IsNative(m.Decl):
                {
                    var args = new List<string>();
                    for (int i = 0; i < c.Args.Count; i++)
                    {
                        var a = c.Args[i].Value!;
                        if (a.Type.Kind == "array" && a is NameExpr { Sym: LocalSym an }) { args.Add(an.CsName.TrimStart('@')); args.Add(an.CsName.TrimStart('@') + "__len"); }
                        else args.Add(E(a));
                    }
                    return $"{Symbol(m)}({string.Join(", ", args)})";
                }
        }
        throw Unsupported(e, DescribeExpr(e));
    }

    static string DescribeExpr(Expr e) => e switch
    {
        CallExpr c => $"calling `{c.Name}`",
        LitExpr { Kind: "str" } or InterpExpr => "strings",
        NewExpr => "allocating objects",
        LambdaExpr => "blocks",
        _ => e.GetType().Name.Replace("Expr", "").ToLowerInvariant(),
    };
}
