using System.Reflection;

namespace Alice.Cli.Commands;

/// <summary>
/// `alice guide [topic]`: prints guide/GUIDE.md (or guide/TOPIC.md) as plain Markdown on stdout, so a person can page
/// it and an AI agent can read it in one call. The files are embedded at build time: the guide always matches the
/// installed Alice. `alice agents [--write]`: the Alice block for a project's AGENTS.md (guide/AGENTS.md).
/// </summary>
public static class GuideCommand
{
    const string Prefix = "Alice.Guide.";

    /// <summary>Topics besides the main guide: lower-case file names (`performance`, `proofs`, `interop`).</summary>
    public static IEnumerable<string> Topics() => Assembly.GetExecutingAssembly().GetManifestResourceNames()
        .Where(n => n.StartsWith(Prefix) && n is not "Alice.Guide.GUIDE.md" and not "Alice.Guide.AGENTS.md")
        .Select(n => n[Prefix.Length..^3].ToLowerInvariant()).Order();

    public static string Text(string topic = "guide")
    {
        using var s = Assembly.GetExecutingAssembly().GetManifestResourceStream(Prefix + topic.ToUpperInvariant() + ".md")
            ?? throw new UsageException($"no guide topic '{topic}'", "topics: " + string.Join(", ", Topics()));
        using var r = new StreamReader(s);
        return r.ReadToEnd();
    }

    public static int Run(List<string> args)
    {
        Console.Out.Write(Text(args.FirstOrDefault(a => !a.StartsWith('-')) ?? "guide"));
        if (args.Count == 0) Console.Out.Write($"\n---\nMore: {string.Join(", ", Topics().Select(t => "`alice guide " + t + "`"))}, `alice agents`.\n");
        return 0;
    }

    public const string Start = "<!-- alice:start (generated by `alice agents --write`; edit outside these markers) -->";
    public const string End = "<!-- alice:end -->";

    /// <summary>AGENTS.md with the Alice block inserted or replaced between the markers; the rest is kept.</summary>
    public static string MergeAgents(string? existing)
    {
        string block = Start + "\n" + Text("agents").TrimEnd() + "\n" + End + "\n";
        if (string.IsNullOrEmpty(existing)) return block;
        int a = existing.IndexOf(Start[..15], StringComparison.Ordinal), b = existing.IndexOf(End, StringComparison.Ordinal);
        if (a >= 0 && b > a) return existing[..a] + block + existing[(b + End.Length)..].TrimStart('\n');
        return existing.TrimEnd() + "\n\n" + block;
    }

    /// <summary>
    /// AGENTS.md with the Alice block (merged, so a project's own notes stay), and CLAUDE.md as a mirror of it: a
    /// single `@AGENTS.md` import, which Claude Code expands, so the two can never drift apart. An existing
    /// CLAUDE.md is left alone.
    /// </summary>
    public static void WriteAgentFiles(string dir)
    {
        string agents = Path.Combine(dir, "AGENTS.md"), claude = Path.Combine(dir, "CLAUDE.md");
        File.WriteAllText(agents, MergeAgents(File.Exists(agents) ? File.ReadAllText(agents) : null));
        if (!File.Exists(claude)) File.WriteAllText(claude, "@AGENTS.md\n");
    }

    public static int Agents(List<string> args)
    {
        if (!args.Contains("--write"))
        {
            Console.Out.Write(Text("agents"));
            return 0;
        }
        WriteAgentFiles(".");
        Console.Out.WriteLine("AGENTS.md: Alice block written (between the alice:start / alice:end markers); CLAUDE.md imports it");
        return 0;
    }
}
