using System.Text;
using System.Text.Json;

namespace Alice.Cli.Projects;

/// <summary>alice.lock: exact NuGet versions resolved by the last restore, pinned on later builds (`alice update` refreshes).</summary>
public static class Lockfile
{
    public const string FileName = "alice.lock";

    /// <summary>The lock lives at the workspace root, or next to a standalone project.</summary>
    public static string PathFor(string projectDir) => System.IO.Path.Combine(Workspace.FindRoot(projectDir) ?? projectDir, FileName);

    public static Dictionary<string, string> Read(string projectDir)
    {
        var p = PathFor(projectDir);
        if (!File.Exists(p)) return new();
        var t = TomlLite.Parse(File.ReadAllText(p));
        return (t.GetValueOrDefault("packages") ?? new()).ToDictionary(kv => kv.Key, kv => (string)kv.Value);
    }

    public static void Write(string dir, Dictionary<string, string> packages)
    {
        var path = System.IO.Path.Combine(dir, FileName);
        var merged = File.Exists(path) ? Read(dir) : new Dictionary<string, string>();
        foreach (var kv in packages) merged[kv.Key] = kv.Value;
        var sb = new StringBuilder("# generated by alice: exact versions from the last restore. `alice update` refreshes.\n[packages]\n");
        foreach (var kv in merged.OrderBy(k => k.Key, StringComparer.Ordinal)) sb.Append($"\"{kv.Key}\" = \"{kv.Value}\"\n");
        File.WriteAllText(path, sb.ToString());
    }

    /// <summary>Resolved versions of the given direct packages from obj/project.assets.json.</summary>
    public static Dictionary<string, string> FromAssets(string assetsPath, IEnumerable<string> direct)
    {
        var want = new HashSet<string>(direct, StringComparer.OrdinalIgnoreCase);
        var result = new Dictionary<string, string>();
        if (!File.Exists(assetsPath)) return result;
        using var doc = JsonDocument.Parse(File.ReadAllText(assetsPath));
        if (!doc.RootElement.TryGetProperty("libraries", out var libs)) return result;
        foreach (var lib in libs.EnumerateObject())
        {
            int slash = lib.Name.IndexOf('/');
            if (slash < 0) continue;
            string name = lib.Name[..slash];
            if (want.Contains(name)) result[want.First(w => string.Equals(w, name, StringComparison.OrdinalIgnoreCase))] = lib.Name[(slash + 1)..];
        }
        return result;
    }
}
