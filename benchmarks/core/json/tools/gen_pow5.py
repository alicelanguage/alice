#!/usr/bin/env python3
# Generates Numbers.Pow5.cs: the 128-bit truncated powers of five used by the Eisel-Lemire fast path
# (same construction as fast_float's script/table_generation.py), q in [-342, 308].
import sys

out = []
def emit(c):
    out.append((c >> 64, c & ((1 << 64) - 1)))

for q in range(-342, 0):
    power5 = 5 ** -q
    z = 0
    while (1 << z) < power5:
        z += 1
    if q >= -27:
        b = z + 127
        c = 2 ** b // power5 + 1
        emit(c)
    else:
        b = 2 * z + 2 * 64
        c = 2 ** b // power5 + 1
        while c >= (1 << 128):
            c //= 2
        emit(c)
for q in range(0, 308 + 1):
    power5 = 5 ** q
    while power5 < (1 << 127):
        power5 *= 2
    while power5 >= (1 << 128):
        power5 //= 2
    emit(power5)

lines = []
lines.append("// <auto-generated> by benchmarks/core/json/tools/gen_pow5.py: 128-bit truncated 5^q, q in [-342, 308] (fast_float construction). </auto-generated>")
lines.append("namespace Alice.Core.Json;")
lines.append("")
lines.append("static partial class Numbers")
lines.append("{")
lines.append("    /// <summary>Pairs (high, low) of the normalized 128-bit truncation of 5^q for q = -342 .. 308.</summary>")
lines.append("    static ReadOnlySpan<ulong> Pow5 => [")
for hi, lo in out:
    lines.append(f"        0x{hi:016X}, 0x{lo:016X},")
lines.append("    ];")
lines.append("}")
sys.stdout.write("\n".join(lines) + "\n")
