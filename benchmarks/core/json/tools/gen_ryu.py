#!/usr/bin/env python3
# Generates DoubleFormat.Tables.cs: Ryu's 125-bit power-of-five tables (Adams, "Ryu: fast float-to-string
# conversion", PLDI 2018): DOUBLE_POW5_INV_SPLIT (q = 0..341) and DOUBLE_POW5_SPLIT (i = 0..325) as (low, high).
import sys

INV_BITS = 125
BITS = 125
inv = []
for i in range(342):
    p = 5 ** i
    j = p.bit_length() - 1 + INV_BITS
    inv.append((1 << j) // p + 1)
pos = []
for i in range(326):
    p = 5 ** i
    n = p.bit_length()
    pos.append(p >> (n - BITS) if n >= BITS else p << (BITS - n))

M = (1 << 64) - 1
out = ["// <auto-generated> by benchmarks/core/json/tools/gen_ryu.py: Ryu's 125-bit tables. </auto-generated>",
       "namespace Alice.Core.Json;", "", "static partial class DoubleFormat", "{",
       "    /// <summary>floor(2^(bitlen(5^q) - 1 + 125) / 5^q) + 1 for q = 0..341, as (low, high).</summary>",
       "    static ReadOnlySpan<ulong> Pow5InvSplit => ["]
for v in inv:
    out.append(f"        0x{v & M:016X}, 0x{v >> 64:016X},")
out.append("    ];")
out.append("")
out.append("    /// <summary>The top 125 bits of 5^i for i = 0..325, as (low, high).</summary>")
out.append("    static ReadOnlySpan<ulong> Pow5Split => [")
for v in pos:
    out.append(f"        0x{v & M:016X}, 0x{v >> 64:016X},")
out.append("    ];")
out.append("}")
sys.stdout.write("\n".join(out) + "\n")
